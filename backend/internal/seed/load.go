package seed

import (
	"context"
	"fmt"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// Load bulk-inserts users and their events in one transaction. It is a no-op
// returning false if the users table already has rows, so the seed job can run
// on every `docker compose up`.
func Load(ctx context.Context, pool *pgxpool.Pool, users []User) (bool, error) {
	tx, err := pool.Begin(ctx)
	if err != nil {
		return false, err
	}
	defer tx.Rollback(ctx) //nolint:errcheck // no-op after commit

	// Self-conflicting lock: concurrent seed runs wait instead of double-seeding.
	if _, err := tx.Exec(ctx, "LOCK TABLE users IN SHARE ROW EXCLUSIVE MODE"); err != nil {
		return false, fmt.Errorf("lock users: %w", err)
	}
	var seeded bool
	if err := tx.QueryRow(ctx, "SELECT EXISTS (SELECT 1 FROM users)").Scan(&seeded); err != nil {
		return false, fmt.Errorf("check users: %w", err)
	}
	if seeded {
		return false, nil
	}

	_, err = tx.CopyFrom(ctx, pgx.Identifier{"users"},
		[]string{"first_name", "last_name", "email", "phone", "city", "language", "email_opt_in", "sms_opt_in", "created_at"},
		pgx.CopyFromSlice(len(users), func(i int) ([]any, error) {
			u := users[i]
			return []any{u.FirstName, u.LastName, u.Email, u.Phone, u.City, u.Language, u.EmailOptIn, u.SMSOptIn, u.CreatedAt}, nil
		}))
	if err != nil {
		return false, fmt.Errorf("copy users: %w", err)
	}

	// Ids are generated by the database; map them back via the unique email.
	ids := make(map[string]int64, len(users))
	rows, err := tx.Query(ctx, "SELECT id, email FROM users")
	if err != nil {
		return false, fmt.Errorf("read user ids: %w", err)
	}
	for rows.Next() {
		var id int64
		var email string
		if err := rows.Scan(&id, &email); err != nil {
			return false, err
		}
		ids[email] = id
	}
	if err := rows.Err(); err != nil {
		return false, fmt.Errorf("read user ids: %w", err)
	}

	var events [][]any
	for _, u := range users {
		for _, e := range u.Events {
			events = append(events, []any{ids[u.Email], e.Type, e.Amount, e.OccurredAt})
		}
	}
	_, err = tx.CopyFrom(ctx, pgx.Identifier{"user_events"},
		[]string{"user_id", "type", "amount", "occurred_at"}, pgx.CopyFromRows(events))
	if err != nil {
		return false, fmt.Errorf("copy events: %w", err)
	}

	return true, tx.Commit(ctx)
}
